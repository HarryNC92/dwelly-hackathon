#!/usr/bin/env bash
# 16:30 runbook. Run from the repo root. Usage: scripts/reality-test.sh [challenge-dir] [concurrency]
# Env: DRY_RUN=1 skips the commit and push and writes to out/rehearsal instead of ANSWERS; ONLY=003,027 limits cases; CUTS=file applies decision-point cuts (rehearsal only).
# 1. pulls the organisers' repo, 2. shows the challenge layout and one index head, 3. runs with numbered folders and the
# global deadline, 4. commits ANSWERS only, 5. prints the commit hash for the form. Nothing in ANSWERS is ever hand-edited.
set -euo pipefail
cd "$(dirname "$0")/.."
SRC="${1:-HackatonPublicCases/HackatonChallendges/Property Management}"
CONC="${2:-10}"
if [[ "$SRC" == http* || "$SRC" == git@* ]]; then
  echo "== cloning the challenge repo"; rm -rf HackatonChallendges && git clone -q --depth 1 "$SRC" HackatonChallendges
  DIR="$(find HackatonChallendges -maxdepth 3 -type d -iname "*property*" | head -1)"
  [ -z "$DIR" ] && { echo "no Property Management folder found; listing:"; find HackatonChallendges -maxdepth 2 -type d; exit 1; }
else
  DIR="$SRC"; [ -d HackatonPublicCases/.git ] && git -C HackatonPublicCases pull -q 2>/dev/null || true
fi
echo "== challenge directory: $DIR"
echo "== cases:"; ls "$DIR" | head -60 | tr '\n' ' '; echo
FIRST="$(ls "$DIR" | head -1)"
echo "== first case layout:"; ls "$DIR/$FIRST"; echo "== index head:"; sed -n 1,40p "$DIR/$FIRST/index.md" | cut -c1-160
echo "== if index.md has an Overview that is context (not an ending), re-run with SHOW_OUTCOME=1"
EXTRA=""; [ "${SHOW_OUTCOME:-0}" = "1" ] && EXTRA="--show-outcome"
OUT="ANSWERS"; [ "${DRY_RUN:-0}" = "1" ] && OUT="out/rehearsal"
ONLYARG=""; [ -n "${ONLY:-}" ] && ONLYARG="--only $ONLY"
CUTARG=""; [ -n "${CUTS:-}" ] && CUTARG="--cuts $CUTS"
rm -rf "$OUT"
echo "== running into $OUT (deadline 22 min, per-case 4 min, concurrency $CONC)"
START=$(date +%s)
pnpm -s tsx src/run.ts --cases "$DIR" --out "./$OUT" --numbered --concurrency "$CONC" --deadline 22 $EXTRA $ONLYARG $CUTARG ${INJECT:+--inject "$INJECT"} 2>&1 | tee out/reality-test.log
echo "== elapsed $(( $(date +%s) - START ))s"; head -40 "$OUT/summary.md"
MISSING=$(OUT_DIR="$OUT" python3 - <<'PY'
import json,os
import sys
out=os.environ.get('OUT_DIR','ANSWERS'); idx=json.load(open(f'{out}/index.json')); only=os.environ.get('ONLY'); ids=set(only.split(',')) if only else None
m=[x['folder'] for x in idx if (ids is None or x['case_id'] in ids) and not os.path.exists(os.path.join(out,x['folder'],'ANSWER.md'))]; print(len(m))
PY
)
echo "== folders missing ANSWER.md: $MISSING (must be 0)"
if [ "${DRY_RUN:-0}" = "1" ]; then echo "== DRY RUN: not committing"; exit 0; fi
git add ANSWERS && git commit -qm "Reality Test results (generated by the frozen system)" && git push -q origin main
echo "== COMMIT HASH FOR THE FORM: $(git rev-parse HEAD)"
